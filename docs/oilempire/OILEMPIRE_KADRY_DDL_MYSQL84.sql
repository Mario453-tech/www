  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_ulid CHAR(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  generation_version VARCHAR(32) NOT NULL,
  creation_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(32) NOT NULL,
  state_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_public_ulid (public_ulid),
  UNIQUE KEY uk_creation (creation_key),
