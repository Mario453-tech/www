<ul>
    <li>Diese Nutzungsbedingungen treten mit ihrer Veröffentlichung in Kraft.</li>
    <li>Für Angelegenheiten, die in diesen Bedingungen nicht geregelt sind, gelten die einschlägigen gesetzlichen Bestimmungen der Europäischen Union.</li>
    <li>Fragen und Support-Anfragen können über das spielinterne Kontakt- und Hilfesystem eingereicht werden.</li>
</ul>
