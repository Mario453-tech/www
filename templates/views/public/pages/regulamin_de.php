<h2>&sect;1 Allgemeine Bestimmungen</h2>
<p>Diese Nutzungsbedingungen regeln die Nutzung des Browserspiels <strong>OilEmpire</strong> (nachfolgend: &bdquo;Spiel&ldquo;), erreichbar unter <strong>oilempire.pl</strong>. Mit der Registrierung eines Benutzerkontos erklärt sich der Spieler mit diesen Bedingungen in vollem Umfang einverstanden.</p>
<p>Die Spielleitung behält sich das Recht vor, die Nutzungsbedingungen jederzeit anzupassen. Über wesentliche &Auml;nderungen werden die Spieler per Ankündigung im Chat oder auf der Hauptseite des Spiels informiert.</p>

<h2>&sect;2 Spielerkonten</h2>
<ul>
    <li>Jeder Spieler darf <strong>nur ein einziges Spielerkonto</strong> besitzen. Das Erstellen zusätzlicher Konten (sog. Multi-Accounts) ist strengstens untersagt.</li>
    <li>Das Konto ist personengebunden &mdash; <strong>Verkauf, Vermietung oder Übertragung von Spielerkonten sind untersagt</strong>.</li>
    <li>Die bei der Registrierung angegebenen Daten (insbesondere die E-Mail-Adresse) müssen wahrheitsgemäß und aktuell sein.</li>
    <li>Der Spieler trägt die alleinige Verantwortung für die Geheimhaltung seines Passworts. Die Spielleitung wird niemals nach Ihrem Passwort fragen.</li>
    <li>Konten, die länger als <strong>90 Tage inaktiv</strong> sind, können nach vorheriger Benachrichtigung gelöscht werden.</li>
</ul>

<h2>&sect;3 Fairplay-Regeln</h2>
<ul>
    <li>Die Nutzung von <strong>Bots, Automatisierungsskripten, Exploits sowie Spielfehlern</strong> zur Erlangung unlauterer Vorteile ist verboten. Festgestellte Fehler sind unverzüglich der Spielleitung zu melden.</li>
    <li>Die <strong>gezielte Sabotage</strong> von Spielmechanismen zur Schädigung anderer Spieler oder der Spielinfrastruktur ist verboten.</li>
    <li><strong>Marktmanipulationen</strong> durch koordinierte Scheinabsprachen oder Nutzung mehrerer Konten zur künstlichen Preisverzerrung sind untersagt.</li>
    <li>Jegliche Versuche von <strong>Hacking, Denial-of-Service-Angriffen oder unbefugtem Zugriff auf die Serverinfrastruktur</strong> führen zum sofortigen permanenten Ausschluss und können strafrechtlich verfolgt werden.</li>
</ul>

<h2>&sect;4 Chat- und Kommunikationsregeln</h2>
<ul>
    <li>Es gilt ein <strong>respektvoller Umgangston</strong> &mdash; Beleidigungen, Schikane, Obszönitäten sowie Diskriminierung anderer Spieler oder der Spielleitung sind untersagt.</li>
    <li>Verboten ist die Verbreitung von Inhalten, die <strong>pornografisch, rassistisch, gewaltverherrlichend</strong> oder nach deutschem und europäischem Recht rechtswidrig sind.</li>
    <li><strong>Spam</strong> &mdash; das wiederholte Versenden identischer Nachrichten oder die Flutung von Kommunikationskanälen &mdash; ist untersagt.</li>
    <li>Die Veröffentlichung von <strong>Werbelinks</strong> oder Verweisen auf Konkurrenzdienste ohne vorherige Genehmigung ist nicht gestattet.</li>
    <li>Die Spielleitung ist berechtigt, regelwidrige Beiträge und Nachrichten zu entfernen.</li>
</ul>

<h2>&sect;5 Sanktionen und Bannsystem</h2>
<p>Bei Verstößen gegen diese Nutzungsbedingungen kann die Spielleitung je nach Schwere des Vergehens folgende Maßnahmen ergreifen:</p>
<ul>
    <li><strong>Verwarnung</strong> &mdash; formeller Hinweis per Chat oder Systemnachricht.</li>
    <li><strong>Chat-Stummschaltung</strong> &mdash; temporäre Sperre der Kommunikationsfunktionen (1 Stunde bis 30 Tage).</li>
    <li><strong>Kontosperre</strong> &mdash; vorübergehender Ausschluss vom Spielzugang (1 bis 30 Tage).</li>
    <li><strong>Permanenter Bann</strong> &mdash; dauerhafter Ausschluss, insbesondere bei Multi-Accounts, Cheating, Serverangriffen oder schweren Verstößen.</li>
</ul>
<p>Gegen eine Sperre kann innerhalb von <strong>7 Tagen</strong> nach Verhängung per E-Mail Beschwerde eingelegt werden. Die Prüfung erfolgt innerhalb von 14 Werktagen.</p>

<h2>&sect;6 Rechte und Pflichten der Spielleitung</h2>
<ul>
    <li>Die Spielleitung ist berechtigt, <strong>Spielparameter, Wirtschaftskennzahlen und Events</strong> zwecks Spielbalance ohne gesonderte Vorankündigung anzupassen.</li>
    <li>Bei nachgewiesener Manipulation können Spielstände, Ressourcen und Konten zurückgesetzt werden.</li>
    <li>Die Spielleitung <strong>haftet nicht für technische Ausfälle</strong>, serverbedingten Datenverlust oder Ergebnisse spielmechanischer Zufallsprozesse (z. B. Marktschwankungen, Unfälle).</li>
    <li>Die Spielleitung verpflichtet sich zum <strong>Schutz personenbezogener Daten</strong> gemäß der DSGVO (GDPR) und gibt diese nicht an unbefugte Dritte weiter.</li>
</ul>

<h2>&sect;7 Events und Turniermodus</h2>
<ul>
    <li>Die Spielleitung kann <strong>zeitlich begrenzte Turniere und Sonder-Events</strong> veranstalten, für die gesonderte Regeln gelten.</li>
    <li>Im Turniermodus können <strong>besondere Restriktionen</strong> greifen (z. B. Bohrturm-Obergrenzen, geschlossene Handelsmärkte). Die Teilnahme gilt als Zustimmung zu diesen Regeln.</li>
    <li>Gewinne und Auszeichnungen in Events sind rein <strong>virtueller Natur</strong> und nicht in reales Geld umtauschbar.</li>
    <li>Die Spielleitung behält sich vor, Events bei Missbrauch oder technischen Störungen vorzeitig zu beenden.</li>
</ul>

