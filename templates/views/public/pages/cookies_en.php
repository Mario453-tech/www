<h2>1. What are Cookies?</h2>
<p>Cookies are small text files placed on your device (computer, tablet, or mobile phone) by your web browser when visiting <strong>OilEmpire</strong> (oilempire.pl).</p>

<h2>2. How We Use Cookies</h2>
<p>In OilEmpire, cookies are utilized for the following functional purposes:</p>
<ul>
    <li><strong>Strictly Necessary:</strong> Maintaining your authenticated player session (<code>PHPSESSID</code>), preventing Cross-Site Request Forgery attacks (<code>csrf_token</code>), and securing account access. These cookies are essential for gameplay and cannot be disabled.</li>
    <li><strong>Preferences:</strong> Retaining your selected interface settings, including your chosen language (English, German, Polish).</li>
    <li><strong>Diagnostics and Stability:</strong> Monitoring gameplay engine reliability and resolving technical errors.</li>
</ul>

