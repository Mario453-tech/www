<h2>4. Managing Your Cookie Choices</h2>
<p>You can adjust your cookie preferences at any time by clicking <strong>Privacy Settings</strong> in the website footer or by adjusting your browser cookie controls.</p>
<p>Please note that disabling strictly necessary cookies may prevent logging in and participating in the game.</p>
