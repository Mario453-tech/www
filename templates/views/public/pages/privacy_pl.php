<h2>1. Administrator danych osobowych</h2>
<p>Administratorem danych osobowych w ramach gry przeglądarkowej <strong>OilEmpire</strong> (oilempire.pl) jest operator serwisu.</p>

<h2>2. Zakres zbieranych danych</h2>
<p>W celu świadczenia usług gry przetwarzamy wyłącznie dane niezbędne do realizacji usługi:</p>
<ul>
    <li>Adres e-mail podany podczas rejestracji konta gracza (niezbędny do aktywacji konta, logowania i odzyskiwania hasła).</li>
    <li>Nazwa użytkownika (nick gracza w grze).</li>
    <li>Adres IP oraz podstawowe dane techniczne przeglądarki (wyłącznie w celach bezpieczeństwa, zapobiegania atakom i nadużyciom).</li>
    <li>Zapisane preferencje gracza (język, zgody na cookies).</li>
</ul>

<h2>3. Podstawa prawna i cel przetwarzania</h2>
<p>Dane przetwarzane są zgodnie z Rozporządzeniem Parlamentu Europejskiego i Rady (UE) 2016/679 (RODO):</p>
<ul>
    <li><strong>Art. 6 ust. 1 lit. b RODO:</strong> Realizacja umowy o świadczenie usług drogą elektroniczną (umożliwienie udziału w grze).</li>
    <li><strong>Art. 6 ust. 1 lit. f RODO:</strong> Prawnie uzasadniony interes administratora (zapewnienie integralności, uczciwości rozgrywki i bezpieczeństwa serwerów).</li>
    <li><strong>Art. 6 ust. 1 lit. a RODO:</strong> Dobrowolna zgoda gracza (np. zapis na opcjonalny newsletter).</li>
</ul>

<h2>4. Okres przechowywania danych</h2>
<p>Dane konta gracza przechowywane są przez okres aktywności konta w grze. W przypadku kont nieaktywnych przez ponad 90 dni, konto wraz z danymi może zostać usunięte. Dane logów bezpieczeństwa przechowywane są przez okres niezbędny do zapewnienia bezpieczeństwa.</p>

<h2>5. Prawa użytkownika</h2>
<p>Każdemu użytkownikowi przysługują prawa wynikające z przepisów RODO:</p>
<ul>
    <li>Prawo dostępu do swoich danych oraz otrzymania ich kopii.</li>
    <li>Prawo do sprostowania (poprawienia) nieprawidłowych danych.</li>
    <li>Prawo do usunięcia danych (&bdquo;prawo do bycia zapomnianym&rdquo;).</li>
    <li>Prawo do ograniczenia przetwarzania danych.</li>
    <li>Prawo do cofnięcia zgody w dowolnym momencie.</li>
</ul>

<h2>6. Bezpieczeństwo danych</h2>
<p>Wszystkie połączenia z serwisem OilEmpire są szyfrowane za pomocą protokołu SSL/TLS (HTTPS). Hasła graczy przechowywane są w postaci zahashowanej przy użyciu bezpiecznych algorytmów kryptograficznych. Nigdy nie udostępniamy danych osobowych podmiotom trzecim w celach marketingowych.</p>
