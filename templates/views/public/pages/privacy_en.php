<h2>1. Data Controller</h2>
<p>The data controller responsible for the online game <strong>OilEmpire</strong> (oilempire.pl) is the platform operator.</p>

<h2>2. Categories of Processed Data</h2>
<p>To provide and operate the game service, we collect and process only strictly necessary information:</p>
<ul>
    <li>The email address submitted upon registration (required for account confirmation, login, and password recovery).</li>
    <li>Chosen player alias (username in the game).</li>
    <li>IP address and technical browser headers (collected solely for cybersecurity, exploit prevention, and abuse mitigation).</li>
    <li>Saved player preferences (interface language, cookie consent choices).</li>
</ul>

<h2>3. Legal Bases and Purposes of Processing</h2>
<p>Data processing complies with Regulation (EU) 2016/679 (GDPR):</p>
<ul>
    <li><strong>Article 6(1)(b) GDPR:</strong> Performance of a contract (facilitating account access and game participation).</li>
    <li><strong>Article 6(1)(f) GDPR:</strong> Legitimate interests (defending system stability, upholding fair play, and preventing cyberattacks).</li>
    <li><strong>Article 6(1)(a) GDPR:</strong> Voluntary user consent (e.g. subscribing to our optional newsletter or setting cookie preferences).</li>
</ul>

<h2>4. Retention Period</h2>
<p>Player account records are retained for the lifetime of the active account. Accounts remaining inactive for over 90 consecutive days may be deleted. Technical security logs are periodically purged once no longer needed for auditing.</p>

<h2>5. Your Data Protection Rights</h2>
<p>Under the GDPR, you hold the following rights regarding your personal data:</p>
<ul>
    <li>Right of access to your stored personal information (Art. 15 GDPR).</li>
    <li>Right to rectification of inaccurate data (Art. 16 GDPR).</li>
    <li>Right to erasure (&ldquo;right to be forgotten&rdquo;, Art. 17 GDPR).</li>
    <li>Right to restriction of processing (Art. 18 GDPR).</li>
    <li>Right to data portability (Art. 20 GDPR).</li>
    <li>Right to withdraw consent at any time (Art. 7(3) GDPR).</li>
</ul>

<h2>6. Data Security</h2>
<p>All network traffic to OilEmpire is protected by modern SSL/TLS encryption (HTTPS). Passwords are never stored in plaintext and are salted and hashed using cryptographic standards. We never monetize or transfer personal data to third parties.</p>
