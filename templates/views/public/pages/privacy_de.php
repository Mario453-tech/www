<h2>1. Verantwortlicher für die Datenverarbeitung</h2>
<p>Verantwortlicher im Sinne der Datenschutz-Grundverordnung (DSGVO) für das Browserspiel <strong>OilEmpire</strong> (oilempire.pl) ist der Plattformbetreiber.</p>

<h2>2. Umfang der verarbeiteten Daten</h2>
<p>Zur Bereitstellung des Spielbetriebs verarbeiten wir ausschließlich die zwingend erforderlichen personenbezogenen Daten:</p>
<ul>
    <li>Die bei der Registrierung angegebene E-Mail-Adresse (erforderlich zur Kontoaktivierung, Authentifizierung und Passwortrücksetzung).</li>
    <li>Der gewählte Spielername (Benutzername im Spiel).</li>
    <li>IP-Adresse und grundlegende technische Metadaten der Browseranfrage (ausschließlich zur Gefahrenabwehr, Betrugsprävention und Serverstabilität).</li>
    <li>Gespeicherte Spracheinstellungen und Cookie-Einwilligungen.</li>
</ul>

<h2>3. Rechtsgrundlagen und Verarbeitungszwecke</h2>
<p>Die Verarbeitung erfolgt im Einklang mit der Verordnung (EU) 2016/679 (DSGVO):</p>
<ul>
    <li><strong>Art. 6 Abs. 1 lit. b DSGVO:</strong> Vertragserfüllung (Bereitstellung des Zugangs und der Funktionen des Browserspiels).</li>
    <li><strong>Art. 6 Abs. 1 lit. f DSGVO:</strong> Berechtigtes Interesse (Schutz der Spielintegrität, Betrugsbekämpfung und Absicherung der IT-Infrastruktur).</li>
    <li><strong>Art. 6 Abs. 1 lit. a DSGVO:</strong> Freiwillige Einwilligung (z. B. Anmeldung zum optionalen Newsletter oder Präferenz-Cookies).</li>
</ul>

<h2>4. Speicherdauer</h2>
<p>Die Kontodaten werden für die Dauer des aktiven Spielerkontos gespeichert. Konten, die länger als 90 Tage inaktiv sind, können gelöscht werden. Sicherheitsrelevante Logdaten werden nach Ablauf der gesetzlichen Aufbewahrungsfristen bzw. nach Wegfall des Schutzzwecks gelöscht.</p>

