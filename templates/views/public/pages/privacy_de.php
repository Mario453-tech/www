<h2>6. Datensicherheit</h2>
<p>Alle Datenübertragungen zur Plattform OilEmpire erfolgen verschlüsselt über das SSL/TLS-Protokoll (HTTPS). Passwörter werden unter Verwendung moderner kryptografischer Hash-Verfahren gespeichert. Wir verkaufen keine personenbezogenen Daten an Dritte.</p>
