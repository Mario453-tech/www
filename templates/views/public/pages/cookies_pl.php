<h2>4. Jak zarządzać plikami cookies?</h2>
<p>Użytkownik może w każdej chwili zmienić swoje ustawienia cookies lub wycofać zgodę, klikając odnośnik <strong>Ustawienia prywatności</strong> w stopce serwisu lub konfigurując ustawienia swojej przeglądarki internetowej.</p>
<p>Zablokowanie niezbędnych plików cookies w przeglądarce może uniemożliwić prawidłowe logowanie i korzystanie z funkcji gry.</p>
