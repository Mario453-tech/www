<h2>1. Czym są pliki cookies?</h2>
<p>Pliki cookies (tzw. ciasteczka) to niewielkie pliki tekstowe wysyłane przez serwer www i zapisywane w pamięci urządzenia końcowego użytkownika (np. na komputerze, tablecie lub smartfonie) podczas korzystania z serwisu <strong>OilEmpire</strong> (oilempire.pl).</p>

<h2>2. W jakim celu używamy cookies?</h2>
<p>W grze OilEmpire pliki cookies wykorzystywane są w następujących celach:</p>
<ul>
    <li><strong>Niezbędne do działania gry:</strong> Utrzymanie aktywnej sesji zalogowanego gracza (<code>PHPSESSID</code>), ochrona przed atakami typu Cross-Site Request Forgery (<code>csrf_token</code>) oraz zapewnienie bezpieczeństwa konta. Te pliki są niezbędne i nie można ich wyłączyć.</li>
    <li><strong>Preferencje:</strong> Zapamiętywanie ustawień wybranych przez gracza, w tym preferowanego języka interfejsu (polski, angielski, niemiecki).</li>
    <li><strong>Analityka i diagnostyka:</strong> Zrozumienie sposobu korzystania z mechanizmów gry w celu poprawy wydajności silnika gry i usuwania błędów.</li>
</ul>

