<h2>1. Was sind Cookies?</h2>
<p>Cookies sind kleine Textdateien, die beim Besuch der Website <strong>OilEmpire</strong> (oilempire.pl) von unserem Webserver an Ihren Browser übermittelt und auf Ihrem Endgerät (Computer, Smartphone oder Tablet) gespeichert werden.</p>

<h2>2. Zu welchem Zweck verwenden wir Cookies?</h2>
<p>Im Spiel OilEmpire setzen wir Cookies für die folgenden Zwecke ein:</p>
<ul>
    <li><strong>Technisch notwendige Cookies:</strong> Aufrechterhaltung der aktiven Spielersitzung (<code>PHPSESSID</code>), Schutz vor bösartigen Cross-Site-Request-Forgery-Angriffen (<code>csrf_token</code>) und Kontosicherheit. Diese Cookies sind für den Spielbetrieb zwingend erforderlich und können nicht deaktiviert werden.</li>
    <li><strong>Präferenz-Cookies:</strong> Speicherung der vom Spieler gewählten Benutzeroberflächen-Einstellungen, insbesondere der bevorzugten Sprache (Deutsch, Englisch, Polnisch).</li>
    <li><strong>Analyse und Stabilität:</strong> Erkennung von Performance-Engpässen und Systemfehlern zur Gewährleistung eines flüssigen Spielablaufs.</li>
</ul>

