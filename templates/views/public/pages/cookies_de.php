<h2>4. Wie können Sie Cookies verwalten?</h2>
<p>Sie können Ihre Cookie-Einstellungen jederzeit über den Link <strong>Datenschutzeinstellungen</strong> in der Fußzeile der Website anpassen oder widerrufen. Zudem können Sie das Speichern von Cookies über die Einstellungen Ihres Browsers steuern.</p>
<p>Bitte beachten Sie, dass das Blockieren technisch notwendiger Cookies den Anmeldevorgang und wesentliche Spielfunktionen beeinträchtigen kann.</p>
