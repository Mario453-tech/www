<h2>&sect;1 Postanowienia ogólne</h2>
<p>Niniejszy Regulamin określa zasady korzystania z gry przeglądarkowej <strong>OilEmpire</strong> (dalej: &bdquo;Gra&rdquo;), dostępnej pod adresem <strong>oilempire.pl</strong>. Rejestracja konta jest równoznaczna z akceptacją poniższych zasad w całości.</p>
<p>Administracja zastrzega sobie prawo do zmiany Regulaminu w dowolnym momencie. O istotnych zmianach gracze będą informowani poprzez ogłoszenie w czacie lub na stronie głównej gry.</p>

<h2>&sect;2 Konta graczy</h2>
<ul>
    <li>Każdy gracz może posiadać <strong>wyłącznie jedno konto</strong>. Zakładanie dodatkowych kont (tzw. multi-konta) jest surowo zabronione.</li>
    <li>Konto jest przypisane do osoby &mdash; <strong>handel, dzierżawa ani odsprzedaż kont jest zabroniona</strong>.</li>
    <li>Dane rejestracyjne (adres e-mail) muszą być prawdziwe i aktualne.</li>
    <li>Gracz ponosi pełną odpowiedzialność za bezpieczeństwo swojego hasła. Administracja nigdy nie prosi o hasło.</li>
    <li>Konta nieaktywne przez ponad <strong>90 dni</strong> mogą zostać usunięte po uprzednim powiadomieniu.</li>
</ul>

<h2>&sect;3 Zasady fair play</h2>
<ul>
    <li>Zabronione jest używanie <strong>botów, skryptów automatyzujących, exploitów i błędów gry</strong> w celu uzyskania przewagi. Znalezione błędy należy zgłaszać administracji.</li>
    <li>Zabronione jest <strong>celowe sabotowanie</strong> mechanizmów gry w celu szkodzenia innym graczom lub samej Grze.</li>
    <li>Zabronione jest <strong>manipulowanie rynkiem</strong> przy użyciu wielu kont lub porozumień mających na celu sztuczne zawyżanie lub zaniżanie cen.</li>
    <li>Wszelkie próby <strong>włamania lub ataku na infrastrukturę</strong> serwera będą skutkować natychmiastowym banem i mogą być zgłoszone odpowiednim służbom.</li>
</ul>

<h2>&sect;4 Zasady czatu i komunikacji</h2>
<ul>
    <li>Obowiązuje <strong>kultura wypowiedzi</strong> &mdash; zakaz wulgaryzmów, obrażania innych graczy, administracji oraz grup społecznych.</li>
    <li>Zakaz publikowania treści <strong>pornograficznych, rasistowskich, nawołujących do przemocy</strong> lub niezgodnych z prawem polskim i UE.</li>
    <li>Zakaz <strong>spamu</strong> &mdash; wielokrotnego wysyłania tych samych wiadomości lub zalewania czatu.</li>
    <li>Zakaz publikowania <strong>linków reklamowych</strong> i odnośników do konkurencyjnych serwisów bez zgody administracji.</li>
    <li>Administracja ma prawo usuwać wiadomości naruszające porządek.</li>
</ul>

<h2>&sect;5 Sankcje i system banicji</h2>
<p>Za naruszenie Regulaminu administracja może zastosować następujące sankcje (proporcjonalnie do przewinienia):</p>
<ul>
    <li><strong>Ostrzeżenie</strong> &mdash; upomnienie widoczne w czacie lub via wiadomość systemowa.</li>
    <li><strong>Wyciszenie czatu</strong> &mdash; czasowa blokada możliwości pisania (1h &ndash; 30 dni).</li>
    <li><strong>Zawieszenie konta</strong> &mdash; czasowa blokada dostępu do Gry (1 &ndash; 30 dni).</li>
    <li><strong>Permanentny ban</strong> &mdash; trwałe usunięcie dostępu, stosowane za: multi-konta, cheating, ataki na serwer, rażące naruszenia regulaminu.</li>
</ul>
<p>Od decyzji o banie można odwołać się drogą mailową w ciągu <strong>7 dni</strong> od jej wydania. Administracja rozpatruje odwołania w ciągu 14 dni roboczych.</p>

<h2>&sect;6 Prawa i obowiązki administracji</h2>
<ul>
    <li>Administracja ma prawo do <strong>modyfikowania parametrów gry</strong> (balans, ceny, eventy) bez wcześniejszego powiadomienia.</li>
    <li>Administracja może <strong>resetować zasoby lub konta</strong> w przypadku udowodnionego naruszenia zasad.</li>
    <li>Administracja <strong>nie odpowiada za przerwy techniczne</strong>, utratę danych wynikającą z awarii serwera ani za decyzje podejmowane przez silnik gry (losowość awarii, rynek ropy itp.).</li>
    <li>Administracja zobowiązuje się do <strong>ochrony danych osobowych</strong> zgodnie z RODO i nie udostępnia ich podmiotom trzecim.</li>
</ul>

<h2>&sect;7 Eventy i tryb turniejowy</h2>
<ul>
    <li>Administracja może organizować <strong>czasowe eventy i turnieje</strong> rządzące się osobnymi zasadami, ogłaszanymi każdorazowo przed startem.</li>
    <li>W trybie turniejowym mogą obowiązywać <strong>dodatkowe ograniczenia</strong> (np. limit odwiertów, zamrożony rynek) &mdash; akceptacja udziału oznacza zgodę na te zasady.</li>
    <li>Nagrody w eventach mają charakter <strong>wirtualny</strong> i nie podlegają wymianie na środki pieniężne.</li>
    <li>Administracja zastrzega prawo do <strong>przedwczesnego zakończenia eventu</strong> w przypadku wykrycia nadużyć.</li>
</ul>

<h2>&sect;8 Postanowienia końcowe</h2>
<ul>
    <li>Regulamin wchodzi w życie z dniem opublikowania.</li>
    <li>W sprawach nieuregulowanych Regulaminem stosuje się przepisy prawa polskiego i europejskiego.</li>
    <li>Wszelkie pytania i zgłoszenia kieruj na adres administracji dostępny w grze.</li>
</ul>
